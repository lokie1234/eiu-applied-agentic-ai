-- Fast retrieval for a mostly-static AI knowledge base.
-- Run this migration after 202609250002_add_folder.sql.

create schema if not exists extensions;
create extension if not exists vector with schema extensions;

create table if not exists public.ai_document_chunks (
  id bigint generated by default as identity primary key,
  knowledge_base_id text not null references public.ai_knowledge_bases(id) on delete cascade,
  document_id text not null references public.ai_documents(id) on delete cascade,
  filename text not null,
  folder text not null default 'Chung',
  chunk_index integer not null,
  page_number integer,
  content text not null,
  embedding extensions.vector(768) not null,
  created_at timestamptz not null default now(),
  unique(document_id, chunk_index)
);

create index if not exists idx_ai_document_chunks_kb
  on public.ai_document_chunks(knowledge_base_id);
create index if not exists idx_ai_document_chunks_embedding
  on public.ai_document_chunks using hnsw (embedding extensions.vector_cosine_ops);

alter table public.ai_document_chunks enable row level security;
drop policy if exists "Service role access for ai_document_chunks" on public.ai_document_chunks;
create policy "Service role access for ai_document_chunks" on public.ai_document_chunks
  for all using (auth.role() = 'service_role');

create or replace function public.match_ai_document_chunks(
  query_embedding extensions.vector(768),
  filter_knowledge_base_id text,
  filter_folder text,
  match_count integer default 6
)
returns table (
  document_id text,
  filename text,
  page_number integer,
  content text,
  similarity double precision
)
language sql
stable
security definer
set search_path = public, extensions
as $$
  select
    chunks.document_id,
    chunks.filename,
    chunks.page_number,
    chunks.content,
    1 - (chunks.embedding <=> query_embedding) as similarity
  from public.ai_document_chunks as chunks
  where chunks.knowledge_base_id = filter_knowledge_base_id
    and chunks.folder = filter_folder
  order by chunks.embedding <=> query_embedding
  limit greatest(1, least(match_count, 12));
$$;

revoke all on function public.match_ai_document_chunks(extensions.vector, text, text, integer) from public;
grant execute on function public.match_ai_document_chunks(extensions.vector, text, text, integer) to service_role;

create table if not exists public.ai_response_cache (
  cache_key text primary key,
  knowledge_base_id text not null references public.ai_knowledge_bases(id) on delete cascade,
  answer text not null,
  sources jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create index if not exists idx_ai_response_cache_expiry
  on public.ai_response_cache(expires_at);

alter table public.ai_response_cache enable row level security;
drop policy if exists "Service role access for ai_response_cache" on public.ai_response_cache;
create policy "Service role access for ai_response_cache" on public.ai_response_cache
  for all using (auth.role() = 'service_role');
